"""Classify the run's oracle disagreements case by case (an analysis after the verdict; it counts toward no rule).

The oracle (`oracle.observe`) is not changed. Each disagreement's output is regenerated by the pinned tool and put
to QCEC again under fixed configurations: the default configuration several times (its checkers race), the
alternating checker alone, the random single-qubit simulation alone, and the ZX checker alone as a further opinion.

    python -m spikes.qopt_audit.disagreements probe <run> <out> [--workers 3]
    python -m spikes.qopt_audit.disagreements report <out>
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

from spikes.qopt_audit import frozen
from spikes.qopt_audit.oracle import ALTERNATING, SIMULATION
from spikes.qopt_audit.run import _rows
from spikes.qopt_p0 import verify
from spikes.qopt_p0.verify import VERIFIED, outcome

KEPT = ("not_equivalent", "strict_parse", "hard_timeout")  # default answers oracle._decide does not re-decide
ZX = {"run_construction_checker": False, "run_simulation_checker": False, "run_alternating_checker": False,
      "run_zx_checker": True}
DIFFERENT = ("not_equivalent", "probably_not_equivalent")  # the ZX checker alone may answer either for a difference
DEFAULT_CALLS = 10
ZX_CALLS = 3

RACE = "race"  # a proof failed: the default raced to no_information and the re-decision could not prove it (change 2)
SECOND_OPINION_TIMEOUT = "second_opinion_timeout"  # proved twice; the alternating checker alone runs out of time
OTHER = "other"


def _timed(original: str, candidate: str, *, workdir: Path, config: dict | None) -> dict:
    verify._WORKER.stop()  # a fresh worker for every call, as the oracle's confirmations use
    t0 = time.monotonic()
    answer = outcome(original, candidate, workdir=workdir, timeout_s=frozen.QCEC_TIMEOUT_S,
                     hard_wall_s=frozen.QCEC_HARD_WALL_S, config=config)
    return {"answer": answer, "seconds": round(time.monotonic() - t0, 3)}


def probe(original: str, candidate: str, *, workdir: Path, default_calls: int = DEFAULT_CALLS,
          zx_calls: int = ZX_CALLS) -> dict:
    """Every QCEC answer on one pair, with its time."""
    return {"default": [_timed(original, candidate, workdir=workdir, config=None) for _ in range(default_calls)],
            "alternating": _timed(original, candidate, workdir=workdir, config=ALTERNATING),
            "simulation": _timed(original, candidate, workdir=workdir, config=SIMULATION),
            "zx": [_timed(original, candidate, workdir=workdir, config=ZX) for _ in range(zx_calls)]}


def classify(result: dict, logged: dict) -> str:
    """Which path gave the logged disagreement, judged from the re-run answers; `other` when ZX does not see the
    difference or nothing re-run explains the log.

    A failed proof is `race` when the default proves the difference on some calls and on others gives an answer that
    `oracle._decide` re-decides (no_information, or probably_not_equivalent), and the alternating checker alone cannot
    decide either, so a raced decision ends undecided. A disagreement proved twice with an undecided second opinion
    is `second_opinion_timeout` when the alternating checker alone cannot decide."""
    if not all(call["answer"] in DIFFERENT for call in result["zx"]):
        return OTHER
    default = Counter(call["answer"] for call in result["default"])
    redecided = sum(n for answer, n in default.items() if answer not in VERIFIED and answer not in KEPT)
    undecided_alone = result["alternating"]["answer"] == "no_information"
    if logged["confirmations"] < frozen.CONFIRM_RUNS:
        return RACE if redecided and default["not_equivalent"] and undecided_alone else OTHER
    if logged["second_opinion"] == "no_information" and default["not_equivalent"] and undecided_alone:
        return SECOND_OPINION_TIMEOUT
    return OTHER


def _done(path: Path) -> set[str]:
    return {json.loads(l)["key"] for l in path.read_text(encoding="utf-8").splitlines() if l.strip()} \
        if path.exists() else set()


def _default_tool(tool: str, text: str) -> str:
    from spikes.qopt_audit.tools import run_tool
    return run_tool(tool, text)


def probe_run(run: Path, out: Path, *, shard: str = "0/1", tool=_default_tool, **kw) -> int:
    """Probe this shard's oracle disagreements (index modulo n); resumable by key."""
    run, out = Path(run), Path(out)
    k, n = (int(x) for x in shard.split("/"))
    log = out / f"probe-{k}.jsonl"
    done = _done(log)
    (out / "work").mkdir(parents=True, exist_ok=True)
    circuits = {p.name: p for p in run.glob("shard-*/circuits/*.qasm")}
    rows = [r for r in _rows(run) if r["kind"] == "oracle_disagreement"]
    probed = 0
    try:
        for index, row in enumerate(rows):
            if index % n != k or row["key"] in done:
                continue
            source = circuits[f"{row['case_kind']}-{row['case']}-{row['seed']}.qasm"].read_text(encoding="utf-8")
            result = probe(source, tool(row["tool"], source), workdir=out / "work", **kw)
            line = {"key": row["key"], "qubits": row["qubits"], "logged": {
                "confirmations": row["confirmations"], "second_opinion": row["second_opinion"],
                "seconds": row["seconds"]}, **result}
            with log.open("a", encoding="utf-8", newline="\n") as handle:
                handle.write(json.dumps(line, sort_keys=True) + "\n")
            probed += 1
    finally:
        verify._WORKER.stop()
    return probed


def report(out: Path) -> str:
    lines = [json.loads(l) for p in sorted(Path(out).glob("probe-*.jsonl"))
             for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]
    lines.sort(key=lambda r: r["key"])
    rows = ["| Case | Qubits | Logged (proofs, second opinion) | Default answers | Alternating | Simulation | ZX | Class |",
            "|---|---|---|---|---|---|---|---|"]
    for r in lines:
        default = Counter(c["answer"] for c in r["default"])
        rows.append("| `{}` | {} | {}, {} | {} | {} ({:.0f} s) | {} ({:.0f} s) | {} | {} |".format(
            r["key"], r["qubits"], r["logged"]["confirmations"], r["logged"]["second_opinion"] or "none",
            ", ".join(f"{a} {c}" for a, c in sorted(default.items())), r["alternating"]["answer"],
            r["alternating"]["seconds"], r["simulation"]["answer"], r["simulation"]["seconds"],
            ", ".join(sorted({c["answer"] for c in r["zx"]})), classify(r, r["logged"])))
    total = Counter(classify(r, r["logged"]) for r in lines)
    busy = sum(c["seconds"] for r in lines for c in [*r["default"], r["alternating"], r["simulation"], *r["zx"]])
    return "\n".join(rows + ["", f"Classes: {dict(sorted(total.items()))}; cases: {len(lines)}; "
                                 f"QCEC busy time: {busy / 3600:.2f} hours"]) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("step", choices=("probe", "report"))
    parser.add_argument("paths", nargs="+")
    parser.add_argument("--workers", type=int, default=3)
    parser.add_argument("--shard", default="")  # "k/n": internal, one worker
    args = parser.parse_args(argv)
    if args.step == "report":
        print(report(Path(args.paths[0])))
    elif args.shard:
        print(probe_run(Path(args.paths[0]), Path(args.paths[1]), shard=args.shard))
    else:
        procs = [subprocess.Popen([sys.executable, "-W", "ignore", "-m", "spikes.qopt_audit.disagreements", "probe",
                                   *args.paths, "--shard", f"{k}/{args.workers}"]) for k in range(args.workers)]
        for proc in procs:
            proc.wait()
        print(report(Path(args.paths[1])))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
